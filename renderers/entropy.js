window.SilentRenderers = window.SilentRenderers || {};
window.SilentRenderers.ENTROPY = function(ctx, w, h, st) {
  'use strict';
  var tel = (st && st.snap && st.snap.visual_telemetry) || {};
  var ot = st && st.snap ? st.snap.open_trade : null;
  var t = st && st.t ? st.t : 0;
  var ent = tel.entropy ?? 0.6;
  var hurst = tel.hurst ?? 0.5;
  var energy = tel.energy_pct ?? 0;
  var phase = tel.phase_state || 'NEUTRAL';
  var entropySeries = tel.entropy_series || [];
  var hurstSeries = tel.hurst_series || [];
  ctx.fillStyle = '#040911';
  ctx.fillRect(0, 0, w, h);
  var leftW = w * 0.45;
  var cx = leftW / 2;
  var cy = h / 2;
  var radius = Math.min(cx, cy) * 0.75;
  ctx.fillStyle = '#0a1a1a';
  ctx.fillRect(0, 0, leftW, h);
  ctx.strokeStyle = ent > 0.5 ? '#06b6d4' : '#a855f7';
  ctx.lineWidth = 3;
  ctx.shadowBlur = ent > 0.5 ? 20 : 15;
  ctx.shadowColor = ent > 0.5 ? '#06b6d4' : '#a855f7';
  ctx.beginPath();
  ctx.arc(cx, cy, radius, 0, Math.PI * 2);
  ctx.stroke();
  ctx.shadowBlur = 0;
  var n = 36;
  for (var i = 0; i < n; i++) {
    var angle = (i / n) * Math.PI * 2 + t * 0.5;
    var r = radius * (0.2 + ent * 0.8);
    var x = cx + Math.cos(angle) * r;
    var y = cy + Math.sin(angle) * r;
    ctx.fillStyle = ent > 0.5 ? '#06b6d4' : '#a855f7';
    ctx.beginPath();
    ctx.arc(x, y, 2.5, 0, Math.PI * 2);
    ctx.fill();
  }
  ctx.fillStyle = '#fff';
  ctx.font = 'bold 16px monospace';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText(energy.toFixed(0) + '% NANG LUONG', cx, cy - 10);
  ctx.fillText(phase, cx, cy + 12);
  var rx = leftW;
  var rw = w - leftW;
  ctx.fillStyle = '#0a1a1a';
  ctx.fillRect(rx, 0, rw, h);
  ctx.strokeStyle = '#334155';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(rx, 0);
  ctx.lineTo(rx, h);
  ctx.stroke();
  var plotX = rx + 40;
  var plotW = rw - 80;
  var plotY = 40;
  var plotH = h - 100;
  ctx.fillStyle = '#94a3b8';
  ctx.font = '12px monospace';
  ctx.textAlign = 'left';
  ctx.fillText('1.0', plotX - 10, plotY);
  ctx.fillText('0.5', plotX - 10, plotY + plotH / 2);
  ctx.fillText('0.0', plotX - 10, plotY + plotH);
  ctx.strokeStyle = '#ef4444';
  ctx.lineWidth = 1;
  ctx.setLineDash([4, 4]);
  var y058 = plotY + plotH * (1 - 0.58);
  var y042 = plotY + plotH * (1 - 0.42);
  ctx.beginPath();
  ctx.moveTo(plotX, y058);
  ctx.lineTo(plotX + plotW, y058);
  ctx.stroke();
  ctx.beginPath();
  ctx.moveTo(plotX, y042);
  ctx.lineTo(plotX + plotW, y042);
  ctx.stroke();
  ctx.setLineDash([]);
  function drawLine(series, color) {
    if (!series || series.length === 0) return;
    ctx.strokeStyle = color;
    ctx.lineWidth = 2;
    ctx.beginPath();
    for (var j = 0; j < series.length; j++) {
      var v = series[j];
      var x = plotX + (j / Math.max(series.length - 1, 1)) * plotW;
      var y = plotY + plotH * (1 - v);
      if (j === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.stroke();
  }
  drawLine(entropySeries, '#06b6d4');
  drawLine(hurstSeries, '#a855f7');
  ctx.fillStyle = '#fff';
  ctx.font = 'bold 14px monospace';
  ctx.textAlign = 'left';
  ctx.fillText('Entropy: ' + ent.toFixed(3), plotX, plotY + plotH + 25);
  ctx.fillStyle = '#a855f7';
  ctx.fillText('Hurst: ' + hurst.toFixed(3), plotX + 120, plotY + plotH + 25);
  ctx.fillStyle = '#fff';
  if (ot) {
    ctx.fillText('TRADE: ' + ot.side + ' @ ' + ot.price, plotX, plotY + plotH + 50);
  }
  ctx.fillStyle = '#fff';
  ctx.font = 'bold 14px monospace';
  ctx.fillText('ENTROPY / HURST', rx + 10, 25);
  ctx.fillStyle = '#64748b';
  ctx.font = '12px monospace';
  ctx.fillText('nguong 0.58 / 0.42', rx + 10, 45);
};